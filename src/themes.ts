export const DEFAULT_THEME_ID = "tasksider-dark";

export function getTheme(id: string): Theme {
  return THEMES.find((t) => t.id === id) || THEMES[0];
}

export function applyTheme(theme: Theme) {
  const root = document.documentElement;
  root.style.setProperty("--bg", theme.bg);
  root.style.setProperty("--bg-top", theme.bgTop);
  root.style.setProperty("--card", theme.card);
  root.style.setProperty("--card-hover", theme.cardHover);
  root.style.setProperty("--input", theme.input);
  root.style.setProperty("--hairline", theme.hairline);
  root.style.setProperty("--hairline-bright", theme.hairlineBright);
  root.style.setProperty("--text", theme.text);
  root.style.setProperty("--muted", theme.muted);
  root.style.setProperty("--accent", theme.accent);
  root.style.setProperty("--accent-soft", theme.accentSoft);
}
